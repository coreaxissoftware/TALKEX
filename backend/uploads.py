def duplicate_for_message(attachment_id: str, new_message_id: str) -> str | None:
    """
    Copy an attachment's file to a new id, bound directly to a different
    message.

    Used for broadcast fan-out: one uploaded file becomes many independent
    messages (one per recipient's DM), and message_id is a single-owner
    binding — the same rule that keeps a normal upload-then-send from being
    re-attached to a second message means one attachment row can't serve two
    messages either. Copying is cheap relative to correctness here: a stray
    half-shared attachment row would be a real authorization hazard (see
    download_file's per-message chat check in main.py).
    """
    source = db.query_one("SELECT * FROM attachments WHERE id = ?", (attachment_id,))
    if source is None:
        return None

    new_attachment_id = f"att_{uuid.uuid4().hex}"
    shutil.copyfile(path_for(attachment_id), path_for(new_attachment_id))

    db.execute(
        """
        INSERT INTO attachments (id, uploader_id, message_id, story_id, file_name,
                                 content_type, size_bytes, created_at)
        VALUES (?, ?, ?, NULL, ?, ?, ?, ?)
        """,
        (new_attachment_id, source["uploader_id"], new_message_id, source["file_name"],
         source["content_type"], source["size_bytes"], time.time()),
    )
    return new_attachment_id


def describe(attachment_id: str) -> dict | None:
    """The metadata a client needs to render an attachment, without the file."""
    row = db.query_one("SELECT * FROM attachments WHERE id = ?", (attachment_id,))
    if row is None:
        return None
    attachment = dict(row)
    return {
        "attachment_id": attachment["id"],
        "file_name": attachment["file_name"],
        "content_type": attachment["content_type"],
        "size_bytes": attachment["size_bytes"],
        "inline": attachment["content_type"] in INLINE_TYPES,
    }


def delete(attachment_id: str):
    """Remove an attachment and its file."""
    destination = path_for(attachment_id)
    if os.path.exists(destination):
        os.remove(destination)
    db.execute("DELETE FROM attachments WHERE id = ?", (attachment_id,))


def sweep_orphans(older_than_seconds: float = 3600) -> int:
    """
    Delete uploads that were never sent.

    Opening the file picker and then changing your mind leaves a file on disk
    with no message pointing at it. Without this they accumulate forever.
    """
    cutoff = time.time() - older_than_seconds
    orphans = db.query_all(
        "SELECT id FROM attachments WHERE message_id IS NULL AND story_id IS NULL "
        "AND avatar_of_user_id IS NULL AND avatar_of_chat_id IS NULL "
        "AND cover_of_user_id IS NULL AND product_of_id IS NULL AND created_at < ?",
        (cutoff,),
    )
    for orphan in orphans:
        delete(orphan["id"])
    return len(orphans)
